const NONE = (r) => {
  const R = REAGS[r];
  if (R.ppt) return E("none", null, "голубой осадок Cu(OH)₂ остался без изменений", "", { keep: 1 });
  if (r === "lit") return E("none", null, "лакмус остался фиолетовым: среда нейтральная", "");
  return E("none", null, R.liq ? "без изменений: окраска реактива не исчезла" : "без видимых изменений", "");
};

export function react(sub, reag, { heat = false, n = 1 } = {}) {
  const v = (T[reag] || {})[sub];
  const e = typeof v === "function" ? v(heat, n) : v;
  return e || NONE(reag);
}

/* Заметно ли различие для задания 24: оба эффекта надёжные (не weak) и разные на вид */
const look = (e) => (e.k === "none" ? "none" : e.k + ":" + (e.c || "") + ":" + (e.ppt || "") + ":" + (e.smell || ""));
export function distinguishes(a, b, r, o) {
  const x = react(a, r, o), y = react(b, r, o);
  if (x.weak || y.weak) return null;   // спорно — не используем ни как ответ, ни как ловушку
  return look(x) !== look(y);
}

/* С учётом нагрева и избытка реактива (человек может нагреть и капнуть ещё): true — различает хотя бы так, false — никак, null — спорно */
const STATES = [{ heat: false, n: 1 }, { heat: true, n: 1 }, { heat: false, n: 3 }, { heat: true, n: 3 }];
export function canTell(a, b, r) {
  const v = STATES.map((o) => distinguishes(a, b, r, o));
  return v.includes(true) ? true : v.every((x) => x === false) ? false : null;
}

