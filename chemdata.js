/* Коллекция реакций: каждая уникальная реакция (по уравнению) — карточка. Открывается, когда реакцию увидел сам */
export function collection() {
  const m = new Map();
  for (const r of Object.keys(REAGS)) for (const s of Object.keys(SUBS)) for (const heat of [false, true]) for (const n of [1, 3]) {
    const e = react(s, r, { heat, n }); if (e.weak || e.k === "none") continue;
    const key = e.eq || e.t; if (!m.has(key)) m.set(key, { key, r, s, heat, e });
  }
  return [...m.values()];
}
