/* Реактив-«ловушка» для пары: реагирует с обоими одинаково — частая ошибка в 24 */

export function makeTask(pair, rnd = Math.random) {
  const [a, b] = rnd() < 0.5 ? pair : [pair[1], pair[0]];
  const all = Object.keys(REAGS).filter((r) => !REAGS[r].ovrOnly);
  const ok = all.filter((r) => canTell(a, b, r) === true), bad = all.filter((r) => canTell(a, b, r) === false);
  if (!ok.length || bad.length < 3) return null;
  const right = ok[Math.floor(rnd() * ok.length)];
  // сначала «ловушки» — реактивы, которые с обоими веществами дают одно и то же видимое изменение
  const traps = bad.filter((r) => react(a, r, { heat: true }).k !== "none");
  const shuf = (x) => x.map((v) => [rnd(), v]).sort((p, q) => p[0] - q[0]).map((p) => p[1]);
  const pool = [...shuf(traps), ...shuf(bad.filter((r) => !traps.includes(r)))];
  return { a, b, right, ok, opts: shuf([right, ...pool.slice(0, 3)]) };
}

